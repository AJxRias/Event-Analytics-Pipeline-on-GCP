#!/usr/bin/env python3
"""
Run every query in sql/analysis and write the results to reports/query_results.md.

The SQL is written in BigQuery Standard SQL. For local runs it is transpiled to DuckDB
with sqlglot, so the exact same files are used in both environments.

    python scripts/run_queries.py                    # DuckDB (local)
    python scripts/run_queries.py --target bigquery  # BigQuery
    python scripts/run_queries.py --only 06          # a single query
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import config  # noqa: E402

SQL_DIR = ROOT / "sql" / "analysis"
PLAIN_INT_COLUMNS = {"event_year", "cohort_year", "hour_of_day", "scan_hour", "tier", "booth_sqm", "days_before_show"}


def to_markdown(df: pd.DataFrame, max_rows: int) -> str:
    df = df.head(max_rows)
    cols = [str(c) for c in df.columns]
    def fmt(col: str, v) -> str:
        if v is None or (not isinstance(v, str) and pd.isna(v)):
            return ""
        if hasattr(v, "item") and not isinstance(v, pd.Timestamp):
            v = v.item()  # numpy scalar -> python
        if isinstance(v, float) and v.is_integer() and not any(k in col for k in ("pct", "_x", "avg")):
            v = int(v)
        if isinstance(v, int) and not isinstance(v, bool) and col not in PLAIN_INT_COLUMNS and "rank" not in col:
            return f"{v:,}"
        if isinstance(v, pd.Timestamp):
            return v.strftime("%Y-%m-%d %H:%M")
        return str(v)

    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(fmt(c, v) for c, v in zip(cols, row)) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def read_query(path: Path) -> tuple[str, str]:
    sql = path.read_text()
    question = next((l.split(":", 1)[1].strip() for l in sql.splitlines() if l.startswith("-- Question")), path.stem)
    return question, sql


class DuckRunner:
    def __init__(self):
        import duckdb
        import sqlglot

        self.sqlglot = sqlglot
        self.con = duckdb.connect(str(config.DUCKDB_PATH), read_only=True)

    def run(self, sql: str) -> pd.DataFrame:
        duck_sql = self.sqlglot.transpile(sql, read="bigquery", write="duckdb")[0]
        return self.con.execute(duck_sql).df()


class BigQueryRunner:
    def __init__(self):
        from google.cloud import bigquery

        self.client = bigquery.Client(project=config.GCP_PROJECT, location=config.BQ_LOCATION)
        self.job_config = bigquery.QueryJobConfig(default_dataset=f"{self.client.project}.{config.BQ_DATASET}")

    def run(self, sql: str) -> pd.DataFrame:
        sql = sql.replace(f"{config.BQ_DATASET}.", f"`{self.client.project}.{config.BQ_DATASET}`.")
        job = self.client.query(sql, job_config=self.job_config)
        df = job.result().to_dataframe()
        print(f"    bytes processed: {job.total_bytes_processed:,}")
        return df


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", default=config.PIPELINE_TARGET, choices=["duckdb", "bigquery"])
    ap.add_argument("--only", help="run only files whose name starts with this prefix")
    ap.add_argument("--max-rows", type=int, default=25)
    ap.add_argument("--out", type=Path, default=ROOT / "reports" / "query_results.md")
    args = ap.parse_args()

    runner = BigQueryRunner() if args.target == "bigquery" else DuckRunner()
    files = sorted(p for p in SQL_DIR.glob("*.sql") if not args.only or p.name.startswith(args.only))
    sections = [f"# Query results\n\nGenerated by `scripts/run_queries.py` against **{args.target}**. "
                f"Each section shows the business question, then the result (first {args.max_rows} rows).\n"]
    failed = 0
    for path in files:
        question, sql = read_query(path)
        t0 = time.perf_counter()
        try:
            df = runner.run(sql)
        except Exception as exc:
            failed += 1
            print(f"FAIL {path.name}: {exc}")
            sections.append(f"## {path.stem}\n\n**Q:** {question}\n\nQuery failed: `{exc}`\n")
            continue
        ms = (time.perf_counter() - t0) * 1000
        print(f"ok   {path.name:<45} {len(df):>5} rows  {ms:7.0f} ms")
        sections.append(f"## {path.stem}\n\n**Q:** {question}\n\n[`sql/analysis/{path.name}`](../sql/analysis/{path.name})"
                        f" · {len(df)} rows\n\n{to_markdown(df, args.max_rows)}\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(sections))
    print(f"\nwrote {args.out}")
    if failed:
        raise SystemExit(f"{failed} queries failed")


if __name__ == "__main__":
    main()
